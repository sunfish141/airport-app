import { chromium } from 'playwright';
import assert from 'node:assert/strict';
import { mkdtemp } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import { join } from 'node:path';

const baseURL = process.env.APP_URL || 'http://127.0.0.1:5173';
const artifacts = await mkdtemp(join(tmpdir(), 'carry-firmware-'));
const browser = await chromium.launch({ headless: true, args: ['--no-sandbox', '--disable-dev-shm-usage'] });
try {
  const page = await browser.newPage({ viewport: { width: 1440, height: 1100 } });
  const errors = [], wasmRequests = [];
  page.on('pageerror', (error) => errors.push(error.message));
  page.on('request', (request) => { if (request.url().includes('controller.wasm')) wasmRequests.push(request.url()); });
  await page.route('https://fonts.googleapis.com/**', (route) => route.abort());
  await page.goto(`${baseURL}/simulation.html`);
  const phone = page.frameLocator('#firmware-phone');
  const state = (value) => phone.locator('#state-label').getByText(value, { exact: true }).waitFor();
  const engine = (value) => page.locator('#engine-state').getByText(value, { exact: true }).waitFor();
  const scan = async (action, pass) => {
    await phone.locator(`#${action}`).click();
    await phone.locator(`[data-demo-pass="${pass}"]`).click();
  };
  await engine('OPEN_FREE');
  assert.equal(await page.locator('#load-error').isVisible(), false);
  assert.equal(wasmRequests.length, 1);
  assert.equal(await page.locator('#command-angle').textContent(), '0°');
  assert.equal(await page.locator('#command-pulse').textContent(), '500 µs');
  const retracted = await page.locator('#latch-bolt').getAttribute('transform');
  assert.equal(await page.locator('#diagram-servo-pin').textContent(), 'GPIO14');
  assert.equal(await page.locator('#diagram-button-pin').textContent(), 'GPIO27');
  assert.doesNotMatch(await page.locator('body').innerText(), /eyelet|endpoint|external LED|fuse|main switch|GPIO32|GPIO33/i);
  for (const id of ['setup-hold', 'sensor-fault', 'jam', 'toggle-cable', 'manual-position']) assert.equal(await page.locator(`#${id}`).count(), 0);
  await page.locator('#connect-firmware').click();
  await phone.locator('#connection-pill').getByText('Connected', { exact: true }).waitFor();
  assert.equal(await phone.locator('#flash').count(), 0);

  await phone.locator('#find').click();
  assert.equal(await phone.locator('#finder-flash').count(), 0);
  await phone.locator('#signal-label').getByText('Strong signal', { exact: true }).waitFor();
  await phone.locator('#location-update').click();
  await phone.locator('#location-status').getByText(/Simulated estimate · Accuracy radius: 80 m/).waitFor();
  await page.locator('#radio-tests summary').click();
  await page.locator('#signal-level').evaluate((element) => { element.value = '-100'; element.dispatchEvent(new Event('input', { bubbles: true })); });
  await phone.locator('#signal-label').getByText('Very weak signal', { exact: true }).waitFor();
  await page.locator('#signal-missing').check();
  await phone.locator('#signal-label').getByText('Signal unavailable', { exact: true }).waitFor();
  await page.locator('#signal-missing').uncheck();
  await phone.locator('#finder').getByRole('button', { name: 'Done', exact: true }).click();
  await page.locator('#radio-tests summary').click();

  const started = Date.now();
  await scan('lock', 1);
  await state('Bag locked');
  assert.equal(await page.locator('#nvs-assigned').textContent(), '1');
  assert.equal(await page.locator('#command-angle').textContent(), '180°');
  const extended = await page.locator('#latch-bolt').getAttribute('transform');
  assert.notEqual(extended, retracted);
  assert.equal(await page.locator('#latch-command').textContent(), 'Latch: extended');
  assert.equal(await page.locator('#pwm-value').textContent(), 'Off');
  await scan('unlock', 2);
  await phone.locator('#notice').getByText(/Wrong pass/).waitFor();
  assert.equal(await page.locator('#nvs-assigned').textContent(), '1');
  assert.equal(await page.locator('#latch-bolt').getAttribute('transform'), extended);
  await scan('unlock', 1);
  await state('Bag released');
  assert.equal(await page.locator('#command-angle').textContent(), '0°');
  assert.equal(await page.locator('#latch-bolt').getAttribute('transform'), retracted);
  assert.ok(Date.now() - started < 60000);
  assert.doesNotMatch(await page.locator('#trace').innerText(), /open=|closed=|microswitch|eyelet/i);

  await page.locator('#physical-button').focus();
  await page.keyboard.down('Space');
  await page.locator('#button-reading').getByText(/^LOW/).waitFor();
  await page.keyboard.up('Space');
  await page.locator('#button-reading').getByText('HIGH', { exact: true }).waitFor();
  await scan('lock', 1);
  await state('Bag locked');
  await page.locator('#service-hold').click();
  await state('Bag released');
  assert.equal(await page.locator('#nvs-assigned').textContent(), '0');

  await scan('lock', 1);
  await state('Bag locked');
  await page.locator('#main-power').click();
  await engine('POWER_OFF');
  assert.equal(await page.locator('#pwm-value').textContent(), 'Off');
  await page.locator('#main-power').click();
  await engine('OPEN_FREE');
  assert.equal(await page.locator('#nvs-assigned').textContent(), '0');
  await page.reload();
  await engine('OPEN_FREE');
  await page.locator('#connect-firmware').click();
  await state('Lock your bag');

  await page.locator('#fault-tests summary').click();
  await page.locator('#storage-failure').check();
  await scan('lock', 1);
  await engine('FAULT');
  await page.locator('#engine-error').getByText('STORAGE', { exact: true }).waitFor();
  assert.equal(await page.locator('#pwm-value').textContent(), 'Off');
  assert.equal(await page.locator('#command-angle').textContent(), '0°');
  await page.locator('#storage-failure').uncheck();
  await page.locator('#service-hold').click();
  await state('Bag released');
  await page.locator('#corrupt-nvs').click();
  await page.locator('#nvs-assigned').getByText('Corrupt', { exact: true }).waitFor();
  await page.locator('#reboot-tag').click();
  await page.locator('#nvs-assigned').getByText('0', { exact: true }).waitFor();
  await engine('OPEN_FREE');
  assert.equal(await page.locator('#nvs-assigned').textContent(), '0');
  await page.locator('#fault-tests summary').click();
  await page.locator('#pause-sim').click();
  const before = await page.locator('#sim-time').textContent();
  await page.locator('#step-sim').click();
  await page.waitForFunction((previous) => document.querySelector('#sim-time').textContent !== previous, before);
  await page.locator('#pause-sim').click();
  await page.locator('#build-info summary').click();
  await page.locator('#timing-config').getByText(/ramp 450 ms · completion 500 ms/).waitFor();
  await page.locator('#build-info summary').click();
  await page.screenshot({ path: join(artifacts, 'desktop.png'), fullPage: true });
  await page.setViewportSize({ width: 390, height: 844 });
  assert.equal(await page.locator('body').evaluate(() => document.documentElement.scrollWidth <= innerWidth), true);
  await page.screenshot({ path: join(artifacts, 'mobile.png'), fullPage: true });
  await page.locator('#clear-trace').click();
  assert.equal(await page.locator('#trace li').count(), 0);
  await page.locator('#reset-workbench').click();
  await engine('OPEN_FREE');
  await page.goto(`${baseURL}/`);
  assert.equal(await page.locator('#demo-label:not([hidden])').count(), 0);
  assert.equal(await page.locator('#flash').count(), 0);
  assert.deepEqual(errors, []);
  console.log('Simulation checks passed: WASM, commanded angle, scan/mismatch/release, D27, service opening, reboot, storage faults, radio inputs, pause/step and responsive layout.');
  console.log(`Screenshots: ${artifacts}`);
} finally { await browser.close(); }
