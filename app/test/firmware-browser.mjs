import { chromium } from 'playwright';
import assert from 'node:assert/strict';
import { mkdtemp } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import { join } from 'node:path';

const baseURL = process.env.APP_URL || 'http://127.0.0.1:5173';
const artifacts = await mkdtemp(join(tmpdir(), 'carry-firmware-'));
const browser = await chromium.launch({ headless: true, args: ['--no-sandbox', '--disable-dev-shm-usage'] });
try {
  const page = await browser.newPage({ viewport: { width: 1600, height: 1100 } });
  const errors = [];
  const wasmRequests = [];
  page.on('pageerror', (error) => errors.push(error.message));
  page.on('request', (request) => { if (request.url().includes('controller.wasm')) wasmRequests.push(request.url()); });
  await page.route('https://fonts.googleapis.com/**', (route) => route.abort());
  await page.goto(`${baseURL}/simulation.html`);
  const phone = page.frameLocator('#firmware-phone');
  const state = (value) => phone.locator('#state-label').getByText(value, { exact: true }).waitFor();
  const engine = (value) => page.locator('#engine-state').getByText(value, { exact: true }).waitFor();
  await engine('OPEN_FREE');
  assert.equal(await page.locator('#load-error').isVisible(), false);
  assert.equal(wasmRequests.length, 1);
  await page.locator('#connect-firmware').click();
  await phone.locator('#connection-pill').getByText('Connected', { exact: true }).waitFor();
  const cycleStart = Date.now();
  await phone.locator('#lock').click();
  await phone.locator('[data-demo-pass="1"]').click();
  await state('Press the tag button');
  assert.equal(await page.locator('#nvs-assigned').textContent(), 'Free');
  assert.equal(await page.locator('#pwm-value').textContent(), 'Detached');
  await page.locator('#setup-hold').click();
  await state('Bag locked');
  assert.equal(await page.locator('#nvs-assigned').textContent(), 'Assigned');
  assert.equal(await page.locator('#toggle-cable').isDisabled(), true);
  assert.ok((await page.locator('#trace').textContent()).includes('NVS committed: assigned, pending Close'));
  assert.ok((await page.locator('#trace').textContent()).includes('PWM enabled: 1600'));
  await phone.locator('#unlock').click();
  await phone.locator('[data-demo-pass="2"]').click();
  await phone.locator('#notice').getByText(/Wrong pass/).waitFor();
  assert.equal(await page.locator('#nvs-assigned').textContent(), 'Assigned');
  await page.reload();
  await engine('LOCKED_ASSIGNED');
  await page.locator('#connect-firmware').click();
  await phone.locator('#unlock').click();
  await phone.locator('[data-demo-pass="1"]').click();
  await engine('MOVING');
  await page.locator('#main-power').click();
  await engine('POWER_OFF');
  assert.equal(await page.locator('#nvs-assigned').textContent(), 'Assigned');
  assert.equal(await page.locator('#pwm-value').textContent(), 'Detached');
  await page.reload();
  await engine('FAULT');
  assert.equal(await page.locator('#nvs-assigned').textContent(), 'Assigned');
  await page.locator('#connect-firmware').click();
  await page.locator('#service-hold').click();
  await state('Bag released');
  assert.equal(await page.locator('#nvs-assigned').textContent(), 'Free');
  assert.ok(Date.now() - cycleStart < 60000, 'Setup and release must fit within one minute in the workbench.');
  await page.locator('.fault-card summary').click();
  await page.locator('#jam').check();
  await page.locator('#setup-hold').click();
  await phone.locator('#lock').click();
  await phone.locator('[data-demo-pass="1"]').click();
  await engine('FAULT');
  assert.ok((await page.locator('#phase-title').textContent()).includes('TIMEOUT'));
  assert.equal(await page.locator('#nvs-assigned').textContent(), 'Assigned');
  assert.equal(await page.locator('#pwm-value').textContent(), 'Detached');
  await page.screenshot({ path: join(artifacts, 'jam-fault.png'), fullPage: true });
  await page.locator('#jam').uncheck();
  await page.locator('#service-hold').click();
  await state('Bag released');
  await page.locator('#sensor-fault').selectOption('1');
  await engine('FAULT');
  assert.ok((await page.locator('#phase-title').textContent()).includes('SENSOR_CONFLICT'));
  await page.locator('#sensor-fault').selectOption('0');
  await page.locator('#service-hold').click();
  await state('Bag released');
  await page.locator('#pause-sim').click();
  await page.locator('#pause-sim').getByText('Resume', { exact: true }).waitFor();
  const before = await page.locator('#sim-time').textContent();
  await page.locator('#step-sim').click();
  await page.waitForFunction((previous) => document.querySelector('#sim-time').textContent !== previous, before);
  await page.locator('#pause-sim').click();
  await page.locator('.trace-card summary').click();
  await page.locator('#show-contacts').check();
  await page.screenshot({ path: join(artifacts, 'workbench.png'), fullPage: true });
  await page.setViewportSize({ width: 390, height: 844 });
  assert.equal(await page.locator('body').evaluate(() => document.documentElement.scrollWidth <= innerWidth), true);
  await page.screenshot({ path: join(artifacts, 'mobile.png'), fullPage: true });
  await page.goto(`${baseURL}/`);
  assert.equal(await page.locator('#demo-label:not([hidden])').count(), 0);
  assert.deepEqual(errors, []);
  console.log('Firmware browser checks passed: actual WASM loaded, QR lock/mismatch, reload persistence, interrupted opening/power recovery, real service hold, jam timeout, sensor conflict, pause/step and responsive layout.');
  console.log(`Screenshots: ${artifacts}`);
} finally { await browser.close(); }
