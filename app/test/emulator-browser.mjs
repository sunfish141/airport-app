import { chromium } from 'playwright';
import assert from 'node:assert/strict';
import { mkdtemp } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import { join } from 'node:path';

const baseURL = process.env.APP_URL || 'http://127.0.0.1:5173';
const artifacts = await mkdtemp(join(tmpdir(), 'carry-emulator-'));
const browser = await chromium.launch({ headless: true, args: ['--no-sandbox', '--disable-dev-shm-usage'] });
try {
  const page = await browser.newPage({ viewport: { width: 1440, height: 1000 } });
  const errors = [];
  page.on('pageerror', (error) => errors.push(error.message));
  await page.route('https://fonts.googleapis.com/**', (route) => route.abort());
  await page.goto(`${baseURL}/emulator.html`);
  const phone = page.frameLocator('#app-frame');
  await phone.getByText('Demo mode · Virtual tag').waitFor();
  await page.locator('#demo-connect').click();
  await phone.locator('#connection-pill').getByText('Connected', { exact: true }).waitFor();
  await page.locator('#demo-setup').click();
  await phone.locator('#lock').click();
  await phone.locator('[data-demo-pass="1"]').click();
  await phone.locator('#state-label').getByText('Locked & assigned', { exact: true }).waitFor();
  await phone.locator('#unlock').click();
  await phone.locator('[data-demo-pass="2"]').click();
  await phone.locator('#notice').getByText(/does not match/).waitFor();
  assert.equal(await phone.locator('#state-label').textContent(), 'Locked & assigned');
  await phone.locator('#unlock').click();
  await phone.locator('[data-demo-pass="1"]').click();
  await phone.locator('#notice').getByText(/Assignment cleared/).waitFor();
  await phone.locator('#storage').click();
  await phone.locator('#state-label').getByText('Closed for storage', { exact: true }).waitFor();
  await page.locator('#demo-service').click();
  await phone.locator('#state-label').getByText('Open & ready', { exact: true }).waitFor();
  await phone.locator('#notice').getByText(/Service opening confirmed/).waitFor();
  await page.locator('.recovery-tools summary').click();
  await page.locator('#obstruction').check();
  await page.locator('#demo-setup').click();
  await phone.locator('#lock').click();
  await phone.locator('[data-demo-pass="1"]').click();
  await phone.locator('#state-label').getByText('Service needed', { exact: true }).waitFor();
  await page.locator('#obstruction').uncheck();
  await page.locator('#demo-service').click();
  await phone.locator('#state-label').getByText('Open & ready', { exact: true }).waitFor();
  for (const value of ['360,800', '390,844', '412,915']) {
    await page.locator('#device-size').selectOption(value);
    const dimensions = await phone.locator('body').evaluate(() => [innerWidth, innerHeight]);
    assert.deepEqual(dimensions, value.split(',').map(Number));
    assert.equal(await phone.locator('body').evaluate(() => document.documentElement.scrollWidth <= innerWidth), true);
  }
  await page.locator('#rotate').click();
  assert.deepEqual(await phone.locator('body').evaluate(() => [innerWidth, innerHeight]), [915, 412]);
  await page.locator('#rotate').click();
  await phone.locator('body').evaluate(() => scrollTo(0, 0));
  await page.screenshot({ path: join(artifacts, 'desktop.png'), fullPage: true });
  await page.setViewportSize({ width: 390, height: 844 });
  assert.equal(await page.locator('body').evaluate(() => document.documentElement.scrollWidth <= innerWidth), true);
  await page.screenshot({ path: join(artifacts, 'mobile.png'), fullPage: true });
  await page.locator('#demo-reboot').click();
  await phone.locator('#connection-pill').getByText('Disconnected', { exact: true }).waitFor();
  await page.locator('#demo-connect').click();
  await phone.locator('#connection-pill').getByText('Connected', { exact: true }).waitFor();
  await page.locator('#demo-reset').click();
  await page.locator('#virtual-connection').getByText('Disconnected · No assignment', { exact: true }).waitFor();
  await page.goto(`${baseURL}/`);
  assert.equal(await page.locator('.demo-banner').count(), 0);
  assert.deepEqual(errors, []);
  console.log('Emulator checks passed: connection, real QR image decoding, mismatch, unlock, storage, obstruction/recovery, viewport presets, rotation, reboot/reset, and normal app isolation.');
  console.log(`Screenshots: ${artifacts}`);
} finally { await browser.close(); }
